import assert from 'node:assert/strict';
import XLSX from 'xlsx';
import { missingTranslationRows, previewTranslations, translationBatches } from '../lib/repeatSentenceTranslations.ts';

const items = [{ id: 'doc-a', ID: '#170 RS', text: 'Read the instructions.' }, { id: 'doc-b', ID: '#171 RS', text: 'Wait here.', vietnameseTranslation: 'Chờ ở đây.' }];
const parse = (s, overwrite = false) => previewTranslations(s, items, overwrite);
const [a, b] = parse('170\tĐọc hướng dẫn.\r\n\n doc-b\tVui lòng chờ.');
assert.equal(a.item.id, 'doc-a'); assert.equal(a.error || a.skip, '');
assert.equal(b.line, 3); assert.ok(b.skip);
assert.equal(parse('#171 RS\tVui lòng chờ.', true)[0].skip, '');
assert.ok(parse('#171\tChờ ở đây.', true)[0].skip);
assert.ok(parse('doc-a\tMột\n#170\tHai')[1].error);
for (const s of ['#170\t ', '170', '#999\tKhông có', '170\tMột\tHai']) assert.ok(parse(s)[0].error);
assert.ok(previewTranslations('170\tBản dịch', [...items, { ...items[0], id: 'other' }], false)[0].error);
console.log('PASS: bulk translation preview, matching, malformed rows, duplicates and overwrite protection.');
const many = Array.from({length: 237}, (_, i) => ({ id: `doc-${i}`, text: `Sentence ${i}`, vietnameseTranslation: i % 2 ? '  ' : '' }));
const missing = missingTranslationRows([...many, items[1]]);
assert.equal(missing.length, many.length);
const book = XLSX.utils.book_new();
XLSX.utils.book_append_sheet(book, XLSX.utils.json_to_sheet(missing), 'Missing translations');
const sheet = XLSX.read(XLSX.write(book, {type: 'buffer', bookType: 'xlsx'})).Sheets['Missing translations'];
const [headers, ...lines] = XLSX.utils.sheet_to_json(sheet, {header: 1, defval: ''});
assert.deepEqual(headers, ['Document ID', 'Nghĩa tiếng Việt', 'Câu tiếng Anh', 'Mã RS']);
assert.equal(lines[236][2], many[236].text);
const ready = previewTranslations(lines.map(([id]) => `${id}\tNghĩa mới`).join('\n'), many, false);
assert.ok(ready.every(r => !r.error && !r.skip));
assert.deepEqual(translationBatches(ready).map(b => b.length), [100,100,37]);
assert.deepEqual(translationBatches(ready).flat(), ready);
console.log('PASS: 237 missing translations exported to XLSX, read back and split into three batches.');